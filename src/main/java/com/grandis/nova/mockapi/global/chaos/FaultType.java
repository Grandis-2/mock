package com.grandis.nova.mockapi.global.chaos;

/**
 * 키를 지정해 걸어두는 결함의 종류.
 *
 * <p>열거형으로 둔다. 요청 본문의 {@code faultType} 이 자유 문자열이면 오타가
 * 조용히 통과해 "걸었는데 발동하지 않는" 결함이 생긴다. 열거형이면 역직렬화 단계에서 400 이 되고
 * 허용값이 오류 메시지에 담긴다.
 */
public enum FaultType {

    /**
     * 등록을 커밋한 뒤 응답 없이 연결을 끊는다.
     *
     * <p>지연·실패율로는 이 상황을 만들 수 없다. 주입한 실패는 모두 커밋 전이라 등록이 저장되지
     * 않기 때문이다. 본 서비스가 "등록 안 됨" 과 "등록됐는데 응답만 잃음" 을 구분해야 하는
     * 결과 불명 상태를 만드는 유일한 수단이다.
     */
    RESPONSE_LOST_AFTER_COMMIT,

    /**
     * 커밋 <b>전에</b> 정한 시간만큼 기다린 뒤 정상 처리한다(느린 성공, NV-261).
     *
     * <p>워커 타임아웃보다 길게 걸면 <b>워커가 포기한 뒤에 커밋되는 등록</b>을 정확히 한 건 만든다. 기다리는 동안은
     * 잠금 전이라 키 조회가 404 이고, 그사이 같은 키 재시도 · 취소 표식이 끼어들 수 있다. 지연 꼬리
     * ({@code tail-over-timeout})는 같은 상황을 확률로 여러 건 만들고, 이 결함은 시연에서 지정한 키 하나로 만든다.
     * 응답 유실은 커밋한 뒤 끊어 키 조회가 처음부터 ACTIVE 라 이 경우가 아니다.
     */
    SLOW_SUCCESS
}
